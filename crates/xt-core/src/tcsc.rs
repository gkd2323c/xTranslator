fn build_tc2sc() -> HashMap<char, char> {
    let mut m = HashMap::with_capacity(200);
    for (tc, sc) in char_pairs() {
        m.insert(tc, sc);
    }
    m
}

fn build_sc2tc() -> HashMap<char, char> {
    let mut m = HashMap::with_capacity(200);
    for (tc, sc) in char_pairs() {
        m.entry(sc).or_insert(tc);
    }
    m
}

pub fn to_simplified(text: &str) -> String {
    let map = tc2sc();
    text.chars().map(|c| map.get(&c).copied().unwrap_or(c)).collect()
}

pub fn to_traditional(text: &str) -> String {
    let map = sc2tc();
    text.chars().map(|c| map.get(&c).copied().unwrap_or(c)).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_to_simplified_common() {
        assert_eq!(to_simplified("\u{9580}"), "\u{95E8}"); // 門→门
        assert_eq!(to_simplified("\u{570B}"), "\u{56FD}"); // 國→国
        assert!(to_simplified("Hello").contains("Hello"));
    }

    #[test]
    fn test_to_traditional_common() {
        assert_eq!(to_traditional("\u{95E8}"), "\u{9580}"); // 门→門
        assert_eq!(to_traditional("\u{56FD}"), "\u{570B}"); // 国→國
    }

    #[test]
    fn test_roundtrip_sc() {
        let orig = "\u{5B66}\u{4E60}"; // 学习
        let tc = to_traditional(orig); // 學習
        let back = to_simplified(&tc); // 学习
        assert_eq!(back, orig);
    }

    #[test]
    fn test_ascii_unchanged() {
        assert_eq!(to_simplified("Hello 123"), "Hello 123");
        assert_eq!(to_traditional("Hello 123"), "Hello 123");
    }
}
